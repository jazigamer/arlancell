-- 3) FUNÇÃO QUE O CLIENTE USA PARA CRIAR PEDIDO --------------------------
-- (o cliente NÃO consegue ler pedidos; só criar através desta função)
create or replace function public.create_order(
  p_cliente jsonb, p_items jsonb, p_subtotal numeric,
  p_discount numeric, p_coupon text, p_total numeric
)
returns table (order_id uuid, order_numero text)
language plpgsql security definer set search_path = public as $$
begin
  return query
  insert into public.orders (numero, cliente, items, subtotal, discount, coupon, total)
  values (
    '#' || lpad(nextval('public.orders_numero_seq')::text, 4, '0'),
    p_cliente, p_items, p_subtotal, p_discount, nullif(p_coupon, ''), p_total
  )
  returning orders.id, orders.numero;
end;
$$;
grant execute on function public.create_order(jsonb, jsonb, numeric, numeric, text, numeric) to anon, authenticated;

-- 4) SEGURANÇA (RLS) -----------------------------------------------------
-- Apaga as policies antigas dessas tabelas e recria do jeito certo.
do $$
declare r record;
begin
  for r in
    select policyname, tablename from pg_policies
    where schemaname = 'public'
      and tablename in ('products','categories','settings','orders','leads')
  loop
    execute format('drop policy %I on public.%I', r.policyname, r.tablename);
  end loop;
end $$;

alter table public.products   enable row level security;
alter table public.categories enable row level security;
alter table public.settings   enable row level security;
alter table public.orders     enable row level security;
alter table public.leads      enable row level security;

-- Todo mundo LÊ: produtos, categorias, configurações da loja
create policy "public read products"   on public.products   for select using (true);
create policy "public read categories" on public.categories for select using (true);
create policy "public read settings"   on public.settings   for select using (true);

-- Só o ADMIN altera
create policy "admin write products"   on public.products   for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admin write categories" on public.categories for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admin write settings"   on public.settings   for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Pedidos: só o admin lê/altera (clientes criam pela função create_order)
create policy "admin all orders" on public.orders for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Leads: qualquer visitante pode cadastrar; só o admin lê/apaga
create policy "public insert leads" on public.leads for insert to anon, authenticated with check (true);
create policy "admin all leads"     on public.leads for all to authenticated using (public.is_admin()) with check (public.is_admin());
